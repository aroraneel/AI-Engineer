# For each scenario below, write a comment saying whether it's better
# modeled as Normal, or as a skewed distribution (Log-normal/Power
# law/Pareto), and briefly why (1 sentence each).

# 1a. The size of files on a typical computer (a few huge files,
#     thousands of tiny ones).
# -> Skewed distribution (Log-normal/Powerlaw/Pareto)
# -> Because most files are small, but a few very large files create a long tail in distribution.

# 1b. Adult resting heart rate in a large healthy population.
# -> Normal distribution
# -> Because heart rate tends to cluster around a central value with relatively symmetric variation.

# 1c. Number of followers per user on a social media platform (most
#     users have few, a handful of celebrities have millions).
# -> Skewed distribution (Powerlaw/Pareto)
# -> Because most users have relatively few followers, but a small number of highly popular users have many millions of followers, creating a long tail in the distribution.