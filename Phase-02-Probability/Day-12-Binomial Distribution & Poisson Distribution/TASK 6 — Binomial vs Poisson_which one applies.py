# 6a. Flipping a coin 20 times and counting how many land heads.
# -> Binomial distribution.
# -> Because, there are fixed number of independent trials (20 flips).

# 6b. Counting how many customers walk into a store in a given hour.
# -> Poisson distribution.
# -> Because, these event is happeing independently,
# and we are counting the number of occurence in a fixed interval.

# 6c. Counting how many defective items are in a batch of 50 manufactured
#     parts, where each part has the same probability of being defective.
# -> Binomial distribution
# -> Because, there are fixed number of independent trials (50 parts).